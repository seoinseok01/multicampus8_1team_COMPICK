-- 기존 COMPICK Oracle DB에 회원 기능을 통합할 때 1회 실행한다.
-- MEMBER 테이블에 nickname 컬럼이 이미 있다면 실행하지 않는다.

WHENEVER SQLERROR EXIT SQL.SQLCODE;

ALTER SESSION SET CURRENT_SCHEMA = COMPICK;

ALTER TABLE MEMBER
    ADD (nickname VARCHAR2(20) DEFAULT 'COMPICK_USER' NOT NULL);

COMMENT ON COLUMN MEMBER.nickname IS '회원 닉네임';

COMMIT;
EXIT;
