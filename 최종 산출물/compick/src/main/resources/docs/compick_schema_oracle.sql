-- 참고
-- 1. updated_at은 INSERT 때만 기본값이 입력된다.
--    수정 시각 자동 갱신은 JPA Auditing으로 처리한다.
-- 2. 회원과 상품은 과거 주문 보존을 위해 물리 삭제보다
--    member_status, sales_status를 이용한 논리 삭제를 권장한다.
-- 3. 같은 회원에게 기본 배송지는 하나만 허용해야 한다.
--    Oracle의 일반 UNIQUE 제약조건만으로 조건부 유일성을 표현하기
--    어려우므로 Service에서 변경 시 기존 기본 배송지를 해제한다.
-- 4. ORDER_ITEM의 order_id와 ORDER_GROUP의 order_id가 일치하는지는
--    주문 생성 Service에서 반드시 검증한다.
-- ============================================================
